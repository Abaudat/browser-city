#[spacetimedb::reducer]
pub fn restore_demo_ping(
    ctx: &ReducerContext,
    rows: Vec<DemoPing>,
    sequence_floor: u64,
) -> Result<(), String> {
    require_owner(ctx)?;
    require_restore_open(ctx)?;
    restore_autoinc_rows(
        rows,
        |r| ctx.db.demo_ping().insert(r),
        |id| {
            ctx.db.demo_ping().id().delete(id);
        },
        "demo_ping",
        sequence_floor,
    )
}

