/// Opens a restore. Refuses unless every table in
/// [`NON_INIT_SEEDED_TABLES`] is empty -- the guard against restoring
/// over a live world. Idempotent-refusing: calling it again while a
/// restore is already open is an error, not a silent no-op, so a
/// half-finished restore is never quietly resumed with a different
/// export.
#[spacetimedb::reducer]
pub fn begin_restore(ctx: &ReducerContext) -> Result<(), String> {
    require_owner(ctx)?;
    if let Some(row) = ctx.db.restore_state().id().find(0)
        && row.open
    {
        return Err("a restore is already open -- call finish_restore first".to_string());
    }
    let mut nonempty: Vec<&str> = Vec::new();
    if ctx.db.demo_ping().iter().next().is_some() {
        nonempty.push("demo_ping");
    }
    if ctx.db.building().iter().next().is_some() {
        nonempty.push("building");
    }
    if ctx.db.building_area().iter().next().is_some() {
        nonempty.push("building_area");
    }
    if ctx.db.character().iter().next().is_some() {
        nonempty.push("character");
    }
    if ctx.db.character_identity().iter().next().is_some() {
        nonempty.push("character_identity");
    }
    if ctx.db.citizen().iter().next().is_some() {
        nonempty.push("citizen");
    }
    if ctx.db.citizen_state().iter().next().is_some() {
        nonempty.push("citizen_state");
    }
    if ctx.db.floor_transition().iter().next().is_some() {
        nonempty.push("floor_transition");
    }
    if ctx.db.placed_object().iter().next().is_some() {
        nonempty.push("placed_object");
    }
    if ctx.db.room().iter().next().is_some() {
        nonempty.push("room");
    }
    if ctx.db.room_area().iter().next().is_some() {
        nonempty.push("room_area");
    }
    if !nonempty.is_empty() {
        return Err(format!(
            "begin_restore refuses a target that is not freshly published -- already has row(s) in: {}",
            nonempty.join(", ")
        ));
    }

    match ctx.db.restore_state().id().find(0) {
        Some(_) => {
            ctx.db
                .restore_state()
                .id()
                .update(RestoreState { id: 0, open: true });
        }
        None => {
            ctx.db
                .restore_state()
                .insert(RestoreState { id: 0, open: true });
        }
    }
    Ok(())
}

/// Closes a restore permanently. Never reopened by calling this again --
/// a second `begin_restore` after `finish_restore` opens a *new* restore
/// (and re-checks every precondition), it does not resume this one.
#[spacetimedb::reducer]
pub fn finish_restore(ctx: &ReducerContext) -> Result<(), String> {
    require_owner(ctx)?;
    require_restore_open(ctx)?;
    ctx.db
        .restore_state()
        .id()
        .update(RestoreState { id: 0, open: false });
    Ok(())
}

/// An auto_inc table's row, reduced to what [`restore_autoinc_rows`]
/// needs: its own id, a copy of itself with a different one, and (only
/// for the case a table has no exported rows at all to reuse, below) one
/// throwaway placeholder value, supplied per table
/// (`impl_autoinc_row!`'s own third argument), never derived. Never
/// `Default` on the row type itself (Tim's direction): that would be a
/// public, meaningless constructor (`Character::default()`, for one)
/// gameplay code could also reach -- restore concerns must not leak into
/// domain types.
trait AutoIncRow: Clone {
    fn id(&self) -> u64;
    fn with_id(&self, id: u64) -> Self;
    fn placeholder() -> Self;
}

/// The shared gap-filling loop this file's module doc describes, generic
/// over one auto_inc table's row type. `insert`/`delete` close over
/// `ctx` and the one table this call restores -- kept as closures rather
/// than a `ctx`/accessor parameter because there is no shared trait
/// across SpacetimeDB's per-table generated accessor types to abstract
/// that part genuinely generically.
///
/// `sequence_floor`, after every row is placed, advances the sequence to
/// at least that position -- never merely to the highest *exported* id.
/// Restoring only up to the restored data's own maximum id can re-issue
/// an id the source already handed out and later deleted (a dangling
/// `character_identity.identity` pointing at a `character_id` no longer
/// present, for one): the next player-created row on the restored
/// database would then collide with that stale reference instead of a
/// fresh id. `sequence_floor` is `st_sequence.allocated` at export time
/// (`scripts/ops/export-world.sh`, `manifest.json`'s own
/// `sequence_floors`) -- a safe upper bound, since nothing above it was
/// ever issued. **Pass `0` for every call but a table's own last batch**
/// -- advancing early would place the sequence past a still-to-come
/// batch's own target ids, which the loop above would then read as an
/// overshoot and abort on.
///
/// The throwaway rows this advance inserts-then-deletes to consume ids
/// must never collide with a real one on a `#[unique]` column
/// (`character_identity.identity`, today): if at least one row was
/// placed, the *last* one placed (`R`) is deleted, cloned with id `0`
/// repeatedly until the generated id reaches the floor, and then
/// re-inserted with its own real, explicit id -- safe, because the
/// sequence is already past it, and `R`'s own unique values cannot
/// collide with the throwaway clones carrying the exact same values,
/// deleted again before the next one is ever inserted. If no row was
/// placed at all (a table with a nonzero floor but nothing exported --
/// rows once existed and were deleted before export), an explicit
/// per-table `placeholder()` is used instead: an empty table has nothing
/// to collide with.
fn restore_autoinc_rows<T: AutoIncRow>(
    rows: Vec<T>,
    mut insert: impl FnMut(T) -> T,
    mut delete: impl FnMut(u64),
    table_name: &str,
    sequence_floor: u64,
) -> Result<(), String> {
    let mut last_placed: Option<T> = None;
    for row in rows {
        let target_id = row.id();
        loop {
            let inserted = insert(row.with_id(0));
            let got = inserted.id();
            if got == target_id {
                last_placed = Some(inserted);
                break;
            } else if got < target_id {
                delete(got);
            } else {
                delete(got);
                return Err(format!(
                    "'{table_name}': the generated id {got} overshot the exported id {target_id} -- exported ids must be strictly increasing and gap-free from the sequence's own position; restore aborted"
                ));
            }
        }
    }
    if sequence_floor > 0 {
        match last_placed {
            Some(r) => {
                delete(r.id());
                loop {
                    let inserted = insert(r.with_id(0));
                    let got = inserted.id();
                    delete(got);
                    if got >= sequence_floor {
                        break;
                    }
                }
                insert(r);
            }
            None => loop {
                let inserted = insert(T::placeholder().with_id(0));
                let got = inserted.id();
                delete(got);
                if got >= sequence_floor {
                    break;
                }
            },
        }
    }
    Ok(())
}

/// `$placeholder` is an explicit literal, never `Default::default()`: a
/// table's own `placeholder()` is only ever reached when that table has
/// no exported rows to reuse instead (`restore_autoinc_rows`'s own doc
/// comment above) -- field values otherwise never matter, since the row
/// is deleted again immediately and nothing else exists yet to collide
/// with.
macro_rules! impl_autoinc_row {
    ($Row:ty, $id_field:ident, $placeholder:expr) => {
        impl AutoIncRow for $Row {
            fn id(&self) -> u64 {
                self.$id_field
            }
            fn with_id(&self, id: u64) -> Self {
                let mut copy = self.clone();
                copy.$id_field = id;
                copy
            }
            fn placeholder() -> Self {
                $placeholder
            }
        }
    };
}

