/// Whether a restore is currently open -- a private, one-row gate no
/// reducer other than the three in this file ever reads or writes.
#[spacetimedb::table(accessor = restore_state)]
pub struct RestoreState {
    #[primary_key]
    id: u8,
    open: bool,
}

fn require_restore_open(ctx: &ReducerContext) -> Result<(), String> {
    match ctx.db.restore_state().id().find(0) {
        Some(row) if row.open => Ok(()),
        _ => Err("no restore is open -- call begin_restore first".to_string()),
    }
}

