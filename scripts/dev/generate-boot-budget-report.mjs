#!/usr/bin/env node
// Story 1.14: turns the raw per-sample JSON run-boot-budget-spike.sh's
// `boot` Playwright project wrote into docs/spikes/1.14-boot-budget.md's
// tables -- the only thing that does this reduction; every number below
// is produced by calling client/tests/e2e/boot-budget/reduce.mjs's pure
// functions over the committed raw JSON, never typed in by hand
// (Quentin's direction).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import {
  decodeRevisitOpened,
  summarize,
  summarizeTerms,
  verdictMet,
} from "../../client/tests/e2e/boot-budget/reduce.mjs";
import {
  CPU_PROFILES,
  DECODE_REVISIT_PERCENTILE,
  DECODE_REVISIT_PROFILE,
  DECODE_REVISIT_ROW_COUNT,
  DECODE_REVISIT_TRIGGER_MS,
  MIN_SAMPLES,
  NETWORK_PROFILES,
  PRE_REGISTERED_BUDGET_MS,
} from "../../client/tests/e2e/boot-budget/profiles.mjs";

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) {
    const key = argv[i].replace(/^--/, "");
    args[key] = argv[i + 1];
  }
  return args;
}

const args = parseArgs(process.argv.slice(2));
const RAW_DIR = args["raw-dir"];
const OUT_FILE = args.out;
const SPACETIME_VERSION = args["spacetime-version"];
const HOST_INFO_FILE = args["host-info"];
const RUN_DATE = args["run-date"] ?? new Date().toISOString();
const PIXI_VERSION = args["pixi-version"] ?? "unknown";
const BROWSER_VERSION = args["browser-version"] ?? "unknown";

if (!RAW_DIR || !OUT_FILE || !SPACETIME_VERSION) {
  console.error(
    "generate-boot-budget-report: usage: --raw-dir <dir> --out <file.md> --spacetime-version <X.Y.Z> [--host-info <file.json>] [--run-date <iso>] [--pixi-version <x.y.z>] [--browser-version <string>]",
  );
  process.exit(1);
}

const hostInfo = HOST_INFO_FILE ? JSON.parse(readFileSync(HOST_INFO_FILE, "utf-8")) : {};

function readJsonFilesMatching(pattern) {
  return readdirSync(RAW_DIR)
    .filter((f) => pattern.test(f))
    .sort()
    .map((f) => JSON.parse(readFileSync(path.join(RAW_DIR, f), "utf-8")));
}

const milestoneRuns = readJsonFilesMatching(/^milestones-.*\.json$/);
const decodeRuns = readJsonFilesMatching(/^decode-.*\.json$/);

const lines = [];
const p = (s = "") => lines.push(s);

p(`<!-- bc:boot-budget-spacetimedb-version ${SPACETIME_VERSION} -->`);
p(
  `<!-- generated by scripts/dev/run-boot-budget-spike.sh on ${RUN_DATE}, host=${hostInfo.hostLabel ?? "unknown"} -->`,
);
p();
p("# Story 1.14: Boot Budget Measured");
p();

// --- Verdict-first, if there is anything to verdict on ---
let overallMissed = false;
let dominantTermName = null;
let dominantTermMs = -Infinity;

const milestoneSummaries = milestoneRuns.map((run) => {
  const summary = summarizeTerms(run.samples);
  const met = verdictMet(summary, PRE_REGISTERED_BUDGET_MS.total);
  if (!met) overallMissed = true;
  for (const [term, stat] of Object.entries(summary.terms)) {
    if (stat.median > dominantTermMs) {
      dominantTermMs = stat.median;
      dominantTermName = term;
    }
  }
  return { network: run.network, cpu: run.cpu, summary, met };
});

const decodeByRowCount = new Map();
for (const run of decodeRuns) {
  const key = run.rowCount;
  if (!decodeByRowCount.has(key)) decodeByRowCount.set(key, []);
  decodeByRowCount.get(key).push(run);
}

let revisitOpened = null;
const revisitRun = decodeRuns.find(
  (r) => r.rowCount === DECODE_REVISIT_ROW_COUNT && r.cpu.name === DECODE_REVISIT_PROFILE,
);
if (revisitRun) {
  const decodeSummary = summarize(revisitRun.samples.map((s) => s.decodeMs));
  const p95 = decodeSummary.p95;
  revisitOpened = decodeRevisitOpened(p95, DECODE_REVISIT_TRIGGER_MS);
}

if (milestoneSummaries.length > 0) {
  if (overallMissed) {
    p(
      `**MISSED.** At least one network/CPU profile's p75 end-to-end time exceeds the ${PRE_REGISTERED_BUDGET_MS.total} ms pre-registered budget. The dominant term is **${dominantTermName}** (median ${dominantTermMs.toFixed(1)} ms across profiles). Per the pre-registered rule, this finding is recorded against A4 and R5 in \`docs/gdd.md\`/\`docs/architecture.md\`, and D6 is reopened.`,
    );
  } else {
    p(
      `**MET.** Every measured network/CPU profile's p75 end-to-end time is at or under the ${PRE_REGISTERED_BUDGET_MS.total} ms pre-registered budget. The dominant term is **${dominantTermName}** (median ${dominantTermMs.toFixed(1)} ms across profiles).`,
    );
  }
} else {
  p("**No milestone samples were found in the raw directory.**");
}

if (revisitOpened !== null) {
  const revisitSummary = summarize(revisitRun.samples.map((s) => s.decodeMs));
  if (revisitOpened) {
    p(
      `**D4's chunking migration is opened.** The ${DECODE_REVISIT_ROW_COUNT}-row decode's ${DECODE_REVISIT_PROFILE}-profile ${DECODE_REVISIT_PERCENTILE} is ${revisitSummary.p95.toFixed(1)} ms, above the pre-registered ${DECODE_REVISIT_TRIGGER_MS} ms trigger.`,
    );
  } else {
    p(
      `D4's revisit trigger is **cleared**: the ${DECODE_REVISIT_ROW_COUNT}-row decode's ${DECODE_REVISIT_PROFILE}-profile ${DECODE_REVISIT_PERCENTILE} is ${revisitSummary.p95.toFixed(1)} ms, at or under the pre-registered ${DECODE_REVISIT_TRIGGER_MS} ms trigger.`,
    );
  }
}
p();

// --- Pre-registered budget (unchanged regardless of what was measured) ---
p("## Pre-registered budget");
p();
p(
  "Written before any number in this run was read (Tim's direction), and never edited afterwards. Total 1000 ms, reference machine:",
);
p();
p("| Term | Budget (ms) |");
p("| --- | --- |");
for (const [term, ms] of Object.entries(PRE_REGISTERED_BUDGET_MS)) {
  p(`| ${term} | ${ms} |`);
}
p();
p(
  `**D4's pre-registered revisit trigger:** the ${DECODE_REVISIT_ROW_COUNT}-row decode passes if its ${DECODE_REVISIT_PROFILE}-profile ${DECODE_REVISIT_PERCENTILE} is <= ${DECODE_REVISIT_TRIGGER_MS} ms. Anything above that opens D4's chunking migration.`,
);
p();
p(`**Verdict statistic:** p75, against the total budget (Quentin's direction).`);
p();

// --- Environment ---
p("## Environment");
p();
p("| | |");
p("| --- | --- |");
p(`| SpacetimeDB | ${SPACETIME_VERSION} |`);
p(`| Pixi | ${PIXI_VERSION} |`);
p(`| Browser | ${BROWSER_VERSION} (Playwright ${args["playwright-version"] ?? "unknown"}) |`);
p(`| Host | ${hostInfo.hostLabel ?? "unknown"} |`);
p(`| CPU | ${hostInfo.cpuModel ?? "unknown"} (${hostInfo.logicalCores ?? "?"} logical cores) |`);
p(
  `| RAM | ${hostInfo.totalMemBytes ? `${(hostInfo.totalMemBytes / 1024 ** 3).toFixed(1)} GiB` : "unknown"} |`,
);
p(`| OS | ${hostInfo.platform ?? "unknown"} ${hostInfo.release ?? ""} |`);
p(`| Run environment | ${hostInfo.ci ? "GitHub Actions runner" : "dev box"} |`);
p(`| Date | ${RUN_DATE} |`);
p();
p(
  `**Caveat, honestly recorded:** this environment's own hardware (see \`Host\`/\`CPU\`/\`RAM\` above) is not itself a mid-range laptop -- it is whatever machine ran \`scripts/dev/run-boot-budget-spike.sh\`. Tim's \`throttled\` CPU profile (CDP 4x) is what makes the result reproducible on any machine, CI included (his own words); the \`reference\` (unthrottled) rows above are this run's own real-machine reading, labelled as such, not a substitute for a literal mid-range laptop's own unthrottled numbers. Re-running this script on one is one command away.`,
);
p();
p("### Network profiles");
p();
p("| Profile | Description |");
p("| --- | --- |");
for (const net of NETWORK_PROFILES) p(`| ${net.name} | ${net.label} |`);
p();
p("### CPU profiles");
p();
p("| Profile | Description |");
p("| --- | --- |");
for (const cpu of CPU_PROFILES) p(`| ${cpu.name} | ${cpu.label} |`);
p();
p(
  "**Does CDP throttling cover WebSocket traffic?** Checked empirically while building this harness (`docs/spikes/1.14-boot-budget.md`'s own commit history carries the probe): with `Network.emulateNetworkConditions` latency raised, the handshake and decode terms against a *local* loopback SpacetimeDB both grew by roughly the configured extra RTT, confirming CDP throttling **does** reach WebSocket frames in this Chromium version -- so the handshake/subscription-decode terms below are not a network-throttling blind spot, at least against loopback. A real TLS+WebSocket upgrade to a non-loopback server (Maincloud included) is not measured here; see the Outstanding section.",
);
p();

// --- Milestone tables ---
p("## Milestones and attribution");
p();
for (const { network, cpu, summary, met } of milestoneSummaries) {
  p(`### ${network.label} / ${cpu.label} (n=${summary.n})`);
  p();
  p("| Term | median (ms) | p75 (ms) | p95 (ms) | max (ms) |");
  p("| --- | --- | --- | --- | --- |");
  for (const [term, stat] of Object.entries(summary.terms)) {
    p(
      `| ${term} | ${stat.median.toFixed(1)} | ${stat.p75.toFixed(1)} | ${stat.p95.toFixed(1)} | ${stat.max.toFixed(1)} |`,
    );
  }
  p(
    `| **total (to player-controllable)** | ${summary.total.median.toFixed(1)} | ${summary.total.p75.toFixed(1)} | ${summary.total.p95.toFixed(1)} | ${summary.total.max.toFixed(1)} |`,
  );
  p(
    `| unattributed remainder | ${summary.remainder.median.toFixed(1)} | ${summary.remainder.p75.toFixed(1)} | ${summary.remainder.p95.toFixed(1)} | ${summary.remainder.max.toFixed(1)} |`,
  );
  p();
  p(
    `Verdict (p75 vs. ${PRE_REGISTERED_BUDGET_MS.total} ms budget): **${met ? "MET" : "MISSED"}**.`,
  );
  const firstSample = milestoneRuns.find(
    (r) => r.network.name === network.name && r.cpu.name === cpu.name,
  )?.samples[0];
  if (firstSample) {
    p(
      `Atlas evidence (first sample): ${firstSample.atlasRequestCount} requests, ${(firstSample.atlasBytes / 1024).toFixed(1)} KiB.`,
    );
  }
  p();
}
if (milestoneSummaries.length === 0) {
  p(
    "No `milestones-*.json` files were found in the raw directory -- run `scripts/dev/run-boot-budget-spike.sh` first.",
  );
  p();
}

// --- Decode sweep tables ---
p("## D4: subscription-decode sweep");
p();
if (decodeByRowCount.size === 0) {
  p(
    "No `decode-*.json` files were found in the raw directory (BC_BOOT_SKIP_DECODE was set, or the sweep has not been run).",
  );
  p();
} else {
  p("| Row count | Network | CPU | n | median (ms) | p75 (ms) | p95 (ms) | max (ms) |");
  p("| --- | --- | --- | --- | --- | --- | --- | --- |");
  const rowCounts = [...decodeByRowCount.keys()].sort((a, b) => a - b);
  for (const rowCount of rowCounts) {
    for (const run of decodeByRowCount.get(rowCount)) {
      const summary = summarize(run.samples.map((s) => s.decodeMs));
      p(
        `| ${rowCount} | ${run.network.label} | ${run.cpu.label} | ${summary.n} | ${summary.median.toFixed(1)} | ${summary.p75.toFixed(1)} | ${summary.p95.toFixed(1)} | ${summary.max.toFixed(1)} |`,
      );
    }
  }
  p();
  const bytesFirst = decodeRuns[0]?.samples?.[0]?.bytesOnWire;
  if (bytesFirst !== undefined) {
    p(
      `Bytes on the wire scale with row count (first sample of each row count): ${rowCounts
        .map((rc) => {
          const run = decodeByRowCount.get(rc)[0];
          return `${rc} rows = ${(run.samples[0].bytesOnWire / 1024).toFixed(1)} KiB`;
        })
        .join(", ")}.`,
    );
    p();
  }
}

p("## Outstanding");
p();
p(
  "- **A real, non-loopback WebSocket upgrade** (Maincloud included) is not measured here -- only a local SpacetimeDB instance is. The CDP-throttling check above confirms the harness's own network emulation reaches WebSocket frames against loopback; a real TLS+WebSocket handshake to a server that is not on the same machine carries its own connection-setup cost this run cannot see.",
);
p(
  "- **The reference-machine rows are a real dev box, not a literal mid-range laptop** (see the Environment section's caveat) -- re-running `scripts/dev/run-boot-budget-spike.sh` on one is one command away.",
);
p(
  "- **The atlas term measures today's boot path**, which streams every character-generator sheet the mounted street crowd references, not a purpose-built sprite atlas -- there is no atlas to measure yet (Tim's direction); this is the evidence for whether building one is worth it, not a measurement of one.",
);
p();

writeFileSync(OUT_FILE, `${lines.join("\n")}\n`, "utf-8");
console.error(`generate-boot-budget-report: wrote ${OUT_FILE}`);
